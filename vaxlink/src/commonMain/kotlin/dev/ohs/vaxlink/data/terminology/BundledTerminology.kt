package dev.ohs.vaxlink.data.terminology

import dev.ohs.vaxlink.generated.resources.Res
import dev.ohs.vaxlink.hcert.LaoDoseMap
import dev.ohs.vaxlink.hcert.PreQualProducts
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock
import org.jetbrains.compose.resources.ExperimentalResourceApi

/** The three terminology layers, loaded once from the bundled copies of the VaxLink IG output. */
class Terminology(val products: PreQualProducts, val doseMap: LaoDoseMap)

/**
 * Reads the terminology the app ships under files/terminology/, generated by nawitech/vaxlink-ig.
 */
class BundledTerminology(
  private val read: suspend (String) -> String = { path -> readBundled(path) }
) {
  private val lock = Mutex()
  private var loaded: Terminology? = null

  suspend fun get(): Terminology =
    lock.withLock {
      loaded
        ?: Terminology(
            products =
              PreQualProducts.fromCodeSystem(read("CodeSystem-PreQualProductIds.json"))
                .withTypesFrom(read("ConceptMap-PreQualProductToTypeLocal.json")),
            doseMap = LaoDoseMap.parse(read("ConceptMap-PreQualTypeToLaoDose.json")),
          )
          .also { loaded = it }
    }

  companion object {
    @OptIn(ExperimentalResourceApi::class)
    suspend fun readBundled(path: String): String =
      Res.readBytes("files/terminology/$path").decodeToString()
  }
}
